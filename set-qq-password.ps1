# 把机器人小号的 QQ 密码存成本机 DPAPI 密文（给 guard_once.ps1 做密码登录用）
#
# 用法：
#   powershell -NoProfile -ExecutionPolicy Bypass -File scripts\napcat\set-qq-password.ps1 -NapCatDir D:\NapCat
#   powershell -NoProfile -ExecutionPolicy Bypass -File scripts\napcat\set-qq-password.ps1 -NapCatDir D:\NapCat -Uin 1000000000 -QuickLogin
#
# 安全说明：
#   - 密文用 Windows DPAPI（当前用户作用域）加密，换用户、换机器都解不开；
#   - 文件落在 <NapCatDir>\secrets\qq_pwd.dpapi，已在 .gitignore 里，不要提交；
#   - 仍然只用小号：密码登录同样属于第三方客户端，违反协议的风险不变。
#   - 加 -QuickLogin 会额外写 <NapCatDir>\secrets\quick_login.env，里面是**明文 MD5**，
#     等同于密码的 API 凭据，脚本会把该文件 ACL 收紧到当前用户。同样不要提交。

param(
    [string]$NapCatDir = 'D:\NapCat',
    [string]$Uin = '',
    [switch]$QuickLogin
)

$dir = Join-Path $NapCatDir 'secrets'
New-Item -ItemType Directory -Path $dir -Force | Out-Null
$target = Join-Path $dir 'qq_pwd.dpapi'

if (Test-Path $target) {
    $ans = Read-Host '已经有密码密文了，要覆盖吗？(y/N)'
    if ($ans -notmatch '^[yY]') { Write-Host '没改。'; exit 0 }
}

$sec = Read-Host '机器人小号的 QQ 密码（输入不回显）' -AsSecureString
if (-not $sec) { Write-Error '没输入密码'; exit 1 }

$enc = ConvertFrom-SecureString $sec
[System.IO.File]::WriteAllText($target, $enc, [System.Text.UTF8Encoding]::new($false))

# 立刻回读验证一次，避免存进去解不开
$back = ConvertTo-SecureString ((Get-Content $target -Raw).Trim())
$plain = ''
$bstr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($back)
try {
    $plain = [Runtime.InteropServices.Marshal]::PtrToStringAuto($bstr)
    Write-Host ("已保存：" + $target + "（长度 " + $plain.Length + "，只有当前 Windows 用户能解）")
} finally {
    [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr)
}

# ---- 可选：写开机快速登录用的 env ----------------------------------
# NapCat 启动时会读 NAPCAT_QUICK_ACCOUNT / NAPCAT_QUICK_PASSWORD_MD5。
# MD5 算法与 guard_once.ps1 的 Invoke-PasswordLogin 一致：明文按 UTF-8 取 MD5，32 位小写。
if ($QuickLogin) {
    if ($Uin -notmatch '^\d{5,12}$') {
        Write-Error '-QuickLogin 需要同时给 -Uin（5-12 位数字），否则写进去的账号是错的'
        exit 1
    }
    $raw = [System.Text.Encoding]::UTF8.GetBytes($plain)
    $md5 = [BitConverter]::ToString([System.Security.Cryptography.MD5]::Create().ComputeHash($raw)).Replace('-', '').ToLower()

    $envFile = Join-Path $dir 'quick_login.env'
    $lines = @(
        'rem generated by set-qq-password.ps1, do not commit',
        ('set "NAPCAT_QUICK_ACCOUNT=' + $Uin + '"'),
        ('set "NAPCAT_QUICK_PASSWORD_MD5=' + $md5 + '"')
    )
    [System.IO.File]::WriteAllLines($envFile, $lines, [System.Text.ASCIIEncoding]::new())

    # 收紧 ACL：去掉继承，只留当前 Windows 用户
    $me = [System.Security.Principal.WindowsIdentity]::GetCurrent().Name
    $icacls = Join-Path $env:SystemRoot 'System32\icacls.exe'
    & $icacls $envFile '/inheritance:r' '/grant:r' ($me + ':(F)') | Out-Null
    Write-Host ("已写入 " + $envFile + "（开机启动时自动快速登录；文件含明文 MD5，勿提交）")
}
