# install.ps1 —— 大肥鱼工具包的引导安装（Windows / PowerShell 5.1+）
#
# 它做三件事：
#   1. 把 scripts\ 下的运行文件复制到 NapCat 目录（默认 D:\NapCat）
#   2. 生成无窗口启动器 guard_hidden.vbs，并注册计划任务 DafeiyuGuard（每 5 分钟）
#   3. 可选：给 dsh-fish-soul 打补丁（sticker_find 工具）
#
# 它**不**做的事（必须由人来做，见 AGENTS.md）：
#   - 安装 QQ / NapCat / DeepSeek Harness
#   - 扫码登录 QQ（二维码必须人拿手机扫）
#   - 填 API Key、写人格卡
#
# 用法：
#   powershell -NoProfile -ExecutionPolicy Bypass -File install.ps1
#   powershell ... -File install.ps1 -NapCatDir "D:\NapCat" -QqDir "C:\Program Files\Tencent\QQNT" -TargetUin 123456789
#
# 卸载：
#   schtasks /Delete /TN DafeiyuGuard /F
#   删除 <NapCatDir> 下复制过去的 start_napcat.bat / qr_portal.py / guard\ 即可

param(
    [string]$NapCatDir  = 'D:\NapCat',
    [string]$QqDir      = 'C:\Program Files\Tencent\QQNT',
    [string]$TargetUin  = '1000000000',
    [int]$PortalPort    = 6210,
    [switch]$SkipTask,
    [switch]$SkipPatch
)

$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot

function Say  ($t) { Write-Host "  $t" }
function Step ($n, $t) { Write-Host ""; Write-Host "[$n] $t" -ForegroundColor Cyan }
function Ok   ($t) { Write-Host "  OK   $t" -ForegroundColor Green }
function Warn ($t) { Write-Host "  !    $t" -ForegroundColor Yellow }

# ── 1. 环境检查 ─────────────────────────────────────────────────────────
Step 1 '环境检查'

if ($PSVersionTable.PSVersion.Major -lt 5) { throw '需要 PowerShell 5.1 或更高版本' }
Ok "PowerShell $($PSVersionTable.PSVersion)"

$qqExe = Join-Path $QqDir 'QQ.exe'
if (Test-Path $qqExe) { Ok "QQ: $qqExe" }
else { Warn "没找到 QQ.exe（$qqExe），之后请用 -QqDir 指定，或装好 QQ 再跑" }

$fishSoul = Join-Path $env:USERPROFILE '.dsh\profiles\desktop\node_modules\dsh-fish-soul'
if (Test-Path $fishSoul) { Ok 'dsh-fish-soul 已安装' }
else { Warn '没找到 dsh-fish-soul，先跑：dsh plugin --profile desktop add dsh-fish-soul' }

$pythonw = Get-Command pythonw.exe -ErrorAction SilentlyContinue
if ($pythonw) { Ok "pythonw: $($pythonw.Source)" }
else { Warn '没找到 pythonw.exe（扫码页需要 Python 3.10+）；没有也能跑，只是掉登录时不会自动开扫码页' }

# ── 2. 复制运行文件 ─────────────────────────────────────────────────────
Step 2 "准备目录 $NapCatDir"

if (-not (Test-Path $NapCatDir)) {
    New-Item -ItemType Directory -Path $NapCatDir -Force | Out-Null
    Ok '已创建目录'
}
if (-not (Test-Path (Join-Path $NapCatDir 'NapCatWinBootMain.exe'))) {
    Warn '这个目录里没有 NapCatWinBootMain.exe —— 确认你已把 NapCat.Shell.Windows.OneKey 解压到这里'
}

$guardDir = Join-Path $NapCatDir 'guard'
New-Item -ItemType Directory -Path $guardDir -Force | Out-Null

Copy-Item (Join-Path $root 'scripts\napcat\start_napcat.bat')  (Join-Path $NapCatDir 'start_napcat.bat')  -Force
Copy-Item (Join-Path $root 'scripts\napcat\qr_portal.py')      (Join-Path $NapCatDir 'qr_portal.py')      -Force
Copy-Item (Join-Path $root 'scripts\napcat\napcat_relogin.py') (Join-Path $NapCatDir 'napcat_relogin.py') -Force
Copy-Item (Join-Path $root 'scripts\guard\guard_once.ps1')     (Join-Path $guardDir 'guard_once.ps1')     -Force
Ok '运行文件已复制'

# 把 start_napcat.bat 里的 QQ 路径换成用户给的
$batPath = Join-Path $NapCatDir 'start_napcat.bat'
$bat = Get-Content $batPath -Raw -Encoding ASCII
$bat = [regex]::Replace($bat, '(?m)^set "QQ_DIR=.*"$', ('set "QQ_DIR=' + $QqDir + '"'))
Set-Content -Path $batPath -Value $bat -Encoding ASCII -NoNewline
Ok "QQ 路径写入 start_napcat.bat：$QqDir"

# ── 3. 生成无窗口启动器 ─────────────────────────────────────────────────
Step 3 '生成 guard_hidden.vbs（无窗口）'

$vbsPath = Join-Path $guardDir 'guard_hidden.vbs'
$vbs = @'
' Generated by install.ps1 - runs guard_once.ps1 with no visible window.
Option Explicit
Dim sh
Set sh = CreateObject("WScript.Shell")
sh.Run "powershell.exe -NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File __SCRIPT__ -NapCatDir __DIR__ -TargetUin __UIN__ -PortalPort __PORT__", 0, True
'@
$vbs = $vbs.Replace('__SCRIPT__', (Join-Path $guardDir 'guard_once.ps1'))
$vbs = $vbs.Replace('__DIR__', $NapCatDir)
$vbs = $vbs.Replace('__UIN__', $TargetUin)
$vbs = $vbs.Replace('__PORT__', "$PortalPort")
Set-Content -Path $vbsPath -Value $vbs -Encoding Unicode -NoNewline
Ok "已生成 $vbsPath"

# ── 4. 注册计划任务 ─────────────────────────────────────────────────────
Step 4 '注册计划任务 DafeiyuGuard（每 5 分钟）'

if ($SkipTask) {
    Warn '已跳过（-SkipTask）'
} else {
    $action = 'wscript.exe "' + $vbsPath + '"'
    schtasks /Delete /TN DafeiyuGuard /F 2>$null | Out-Null
    schtasks /Create /TN DafeiyuGuard /TR $action /SC MINUTE /MO 5 /F | Out-Host
    Ok '已注册；用 schtasks /Query /TN DafeiyuGuard /V /FO LIST 查看'
}

# ── 5. 给 fish-soul 打补丁（可选）──────────────────────────────────────
Step 5 '给 dsh-fish-soul 打补丁（sticker_find）'

if ($SkipPatch) {
    Warn '已跳过（-SkipPatch）'
} elseif (-not (Test-Path $fishSoul)) {
    Warn '没有 dsh-fish-soul，跳过'
} else {
    $py = Get-Command python.exe -ErrorAction SilentlyContinue
    if (-not $py) {
        Warn '没找到 python.exe，跳过（补丁不是必须的）'
    } else {
        & $py.Source (Join-Path $root 'patches\fish-soul\apply_patches.py')
        if ($LASTEXITCODE -eq 0) { Ok '补丁已应用（--revert 可还原）' }
        else { Warn "补丁失败，退出码 $LASTEXITCODE" }
    }
}

# ── 6. 下一步 ───────────────────────────────────────────────────────────
Write-Host ""
Write-Host '安装完成。接下来必须由人来做：' -ForegroundColor Green
Say '1) 第一次启动 NapCat（双击或 WMI 分离启动）：'
Say ('     cmd /c start "" /min "' + $NapCatDir + '\start_napcat.bat"')
Say ('2) 打开扫码页： http://127.0.0.1:' + $PortalPort)
Say ('     或  python "' + (Join-Path $NapCatDir 'qr_portal.py') + '" --napcat-dir "' + $NapCatDir + '" --port ' + $PortalPort)
Say '3) 用 QQ 小号扫码；登录后确认 6099 和 6200 都在监听：'
Say '     Get-NetTCPConnection -State Listen -LocalPort 6099,6200'
Say '4) 在 DSH 里把 fish-soul 的 wsUrl 设成 ws://127.0.0.1:6200（examples/fish-soul-config.example.json）'
Say '5) 填模型 API Key、导入人格卡（examples/persona.example.json）'
Write-Host ""
Write-Host '详细步骤见 docs/deploy.md；故障见 docs/troubleshooting.md。' -ForegroundColor Gray
